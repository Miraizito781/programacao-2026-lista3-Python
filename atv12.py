#12. Peça a leitura de um número inteiro e exiba na tela o dobro, o triplo e a metade desse número. 
print("Digite um número: ")
num = int(input())
dobro = num * 2
triplo = num * 3
metade = num / 2
print(f"O número informado tem como dobro: {dobro} , tem como triplo: {triplo}, e tem como metade: {metade}")